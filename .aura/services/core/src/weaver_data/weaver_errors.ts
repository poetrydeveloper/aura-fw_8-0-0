export class WeaverErrorFactory {
    /**
     * Генерирует бронебойную промышленную инструкцию при обнаружении необёрнутого Luau-кода
     */
    public static createUnwrappedCodeError(offendingText: string): string {
        return `
[AURA-CRITICAL-SVO-ERROR] Обнаружен голый, необёрнутый Luau-код: "${offendingText}"
| 
| Причина: ИИ-Исполнитель вставил вызов функции прямо внутрь JSX-структуры тегов, забыв изолировать его скобками.
| Из-за этого нарушается математический баланс фигурных скобок при генерации финального класса TypeScript.
| 
| ИНСТРУКЦИЯ ДЛЯ ИИ-АРХИТЕКТОРА ПО ИСПРАВЛЕНИЮ РАКУШКИ:
| Обязательно оберни любые сырые строки print(), warn() или вызовы методов в фигурные скобки { ... } внутри метода render().
| Фигурные скобки гарантируют, что компилятор ts-morph воспримет этот текст как Expression-блок.
| 
| Пример правильной архитектурной разметки:
|   <NestedQuery target="GALAXY_PLAYER">
|       {
|           print("Cosmic Collision detected!");
|           warn("Applying planetary damage payload!");
|       }
|   </NestedQuery>
| 
| Исправь ракушку на хосте и перезапусти конвейер деплоя. Сборка аннулирована.
`;
    }
}
